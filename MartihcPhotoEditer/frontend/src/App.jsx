import React, { useState } from 'react';
import { Upload, Image as ImageIcon, Wand2, Download, Settings2, Sparkles, RefreshCcw } from 'lucide-react';
import { motion, AnimatePresence } from 'framer-motion';
import InteractiveCanvas from './components/InteractiveCanvas';
import FilterSidebar from './components/FilterSidebar';
import ArtStyleSidebar from './components/ArtStyleSidebar';
import { useGeminiFilters } from './hooks/useGeminiFilters';
import { baseUrl } from './endPoints';
import './App.css';

function App() {
  const canvasRef = React.useRef(null);
  const [image, setImage] = useState(null);
  const [originalImage, setOriginalImage] = useState(null);
  const { generateFilters, isGenerating, error } = useGeminiFilters();
  const [isDragging, setIsDragging] = useState(false);
  const [showFilters, setShowFilters] = useState(false);
  const [showArtStyle, setShowArtStyle] = useState(false);
  const [filters, setFilters] = useState({
    exposure: 0,
    contrast: 0,
    saturation: 0,
    temperature: 0,
    tint: 0,
    highlights: 0,
    shadows: 0,
    vignette: 0
  });

  const handleDragOver = (e) => {
    e.preventDefault();
    setIsDragging(true);
  };

  const handleDragLeave = (e) => {
    e.preventDefault();
    setIsDragging(false);
  };

  const handleDrop = (e) => {
    e.preventDefault();
    setIsDragging(false);
    
    if (e.dataTransfer.files && e.dataTransfer.files[0]) {
      const file = e.dataTransfer.files[0];
      handleFile(file);
    }
  };

  const handleFileSelect = (e) => {
    if (e.target.files && e.target.files[0]) {
      handleFile(e.target.files[0]);
    }
  };

  const handleFile = (file) => {
    if (file.type.startsWith('image/')) {
      const url = URL.createObjectURL(file);
      setImage(url);
      setOriginalImage(url); // Save the original image so we can reset to it
    } else {
      alert('Please upload an image file');
    }
  };

  const handleGenerate = async (prompt) => {
    if (!image) return;
    try {
      const newFilters = await generateFilters(prompt, filters);
      if (newFilters) {
        // Merge the new filters generated by Gemini into the existing ones
        setFilters(prev => ({
          ...prev,
          ...newFilters
        }));
      }
    } catch (err) {
      console.error(err);
      alert(err.message || "Failed to generate filters via Gemini.");
    }
  };

  return (
    <div className="app-container">
      {/* Header */}
      <header className="glass-panel flex-between px-6 py-4 mx-4 mt-4">
        <div className="flex-center" style={{ gap: '12px' }}>
          <div className="logo-icon flex-center">
            <Sparkles size={24} color="var(--text-primary)" />
          </div>
          <h1 className="text-gradient-accent" style={{ fontSize: '24px', margin: 0 }}>ArtStyleTransfer</h1>
        </div>
        
        <div className="flex-center" style={{ gap: '16px' }}>
          {image && (
            <>
              <button 
                className={`glass-button ${showFilters ? 'primary' : ''}`}
                onClick={() => setShowFilters(!showFilters)}
              >
                <Settings2 size={18} /> Filters
              </button>
              <button 
                className={`glass-button ${showArtStyle ? 'primary' : ''}`}
                onClick={() => setShowArtStyle(!showArtStyle)}
              >
                <Wand2 size={18} /> Art Style
              </button>
              <button 
                className="glass-button"
                onClick={() => {
                  if (originalImage) {
                    setImage(originalImage);
                    setFilters({ exposure: 0, contrast: 0, saturation: 0, temperature: 0, tint: 0, highlights: 0, shadows: 0, vignette: 0 });
                  }
                }}
              >
                <RefreshCcw size={18} /> Reset
              </button>
              <button 
                className="glass-button primary"
                onClick={() => {
                  if (canvasRef.current) canvasRef.current.exportImage();
                }}
              >
                <Download size={18} /> Export
              </button>
            </>
          )}
        </div>
      </header>

      {/* Main Workspace */}
      <main className="workspace px-4 py-6">
        <AnimatePresence mode="wait">
          {!image ? (
            <motion.div 
              key="uploader"
              initial={{ opacity: 0, y: 20 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0, scale: 0.95 }}
              transition={{ duration: 0.3 }}
              className={`uploader-container glass-panel ${isDragging ? 'dragging' : ''}`}
              onDragOver={handleDragOver}
              onDragLeave={handleDragLeave}
              onDrop={handleDrop}
            >
              <div className="uploader-content flex-center">
                <div className="icon-wrapper">
                  <Upload size={48} color="var(--accent-primary)" />
                </div>
                <h2>Upload your image</h2>
                <p className="text-muted">Drag and drop or click to browse</p>
                
                <input 
                  type="file" 
                  id="file-upload" 
                  accept="image/*" 
                  onChange={handleFileSelect} 
                  style={{ display: 'none' }} 
                />
                <label htmlFor="file-upload" className="glass-button primary mt-4">
                  <ImageIcon size={18} /> Select Image
                </label>
              </div>
            </motion.div>
          ) : (
            <motion.div 
              key="canvas-wrapper"
              initial={{ opacity: 0, scale: 0.95 }}
              animate={{ opacity: 1, scale: 1 }}
              transition={{ duration: 0.3 }}
              style={{ width: '100%', height: '100%' }}
            >
              <InteractiveCanvas 
                ref={canvasRef}
                image={image} 
                filters={filters}
                onRefine={() => {}}
                onGenerate={handleGenerate}
              />
              {error && (
                <div style={{
                  position: 'absolute', top: '16px', left: '50%', transform: 'translateX(-50%)',
                  background: 'rgba(239, 68, 68, 0.9)', padding: '8px 16px', borderRadius: '8px',
                  color: 'white', zIndex: 101, fontWeight: 'bold'
                }}>
                  {error}
                </div>
              )}
              {isGenerating && (
                <div style={{
                  position: 'absolute', inset: 0, 
                  background: 'rgba(0,0,0,0.5)', 
                  display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center',
                  zIndex: 100, backdropFilter: 'blur(4px)', color: 'white', borderRadius: 'var(--radius-lg)'
                }}>
                  <div className="animate-spin mb-4"><Sparkles size={32} /></div>
                  <h3 className="text-gradient-accent">AI is generating your perfect edit...</h3>
                </div>
              )}
              <FilterSidebar 
                isOpen={showFilters} 
                onClose={() => setShowFilters(false)} 
                filters={filters}
                setFilters={setFilters}
              />
              <ArtStyleSidebar 
                isOpen={showArtStyle} 
                onClose={() => setShowArtStyle(false)}
                image={image}
                onApplyStyle={(newImageUrl) => {
                  if (newImageUrl) setImage(newImageUrl);
                }}
              />
            </motion.div>
          )}
        </AnimatePresence>
      </main>
    </div>
  );
}

export default App;
